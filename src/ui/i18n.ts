export const MESSAGES: Record<Language, Record<MessageKey, string>> = { en, pt };
export const LOCALE: Record<Language, string> = { pt: 'pt-BR', en: 'en-US' };
const PLACEHOLDER = /\{(\w+)\}/g;
const STATUS_KEY: Record<Status | 'new', MessageKey> = { new: 'status.new', empty: 'status.empty', working: 'status.working', waiting: 'status.waiting', review: 'status.review', approval: 'status.approval', backoff: 'status.backoff' };
const EVENT_KEY: Record<Exclude<WorkerEventKind, 'tool'>, MessageKey> = {
  starting: 'event.starting', manualStart: 'event.manualStart', prompt: 'event.prompt', waiting: 'event.waiting', pr: 'event.pr', turn: 'event.turn',
  continuing: 'event.continuing', ask: 'event.ask', background: 'event.background', apiError: 'event.apiError',
};

let current: Language = 'en';

export function setLanguage(language: Language): void {
  current = language;
}

/** A count in the current language's digits (#797): 4.000 in pt, 4,000 in en. */
export const formatCount = (n: number): string => n.toLocaleString(LOCALE[current]);

/** The text for `key` in the current language; `{name}` placeholders are filled from `vars` and left alone when there is none. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[current][key];
  if (!vars) return text; // the prompt hint carries literal {id} / {number}: untouched
  return text.replace(PLACEHOLDER, (match, name: string) => (Object.hasOwn(vars, name) ? String(vars[name]) : match));
}

export const statusText = (status: Status | 'new'): string => t(STATUS_KEY[status]);

/** A family with a `.one` / `.other` variant: the main process's stop confirmation, by how many workers a stop would kill (#242), or a diff's file count (#270), or how many tasks a stage's
 *  view filter hides (#374), or a run command's own variables (#511), or the commits a Restart discards (#580). */
export type PluralFamily = 'settings.stages.deleteMoves.move' | 'main.confirm.quit' | 'review.comments' | 'review.openThreads' | 'main.confirm.restart' | 'diff.files' | 'stage.hidden' | 'settings.commands.vars' | 'worktrees.count' | 'worktrees.orphanCount' | 'copy.messages' | 'copy.uncommitted' | 'search.count' | 'restart.commits' | 'editor.diag.errors' | 'editor.diag.warnings' | 'editor.diag.infos' | 'settings.memory.lessons' | 'settings.memory.citedTimes' | 'settings.memory.lessonsCited' | 'settings.memory.days' | 'pr.commits' | 'pr.review.along' | 'pr.merge.facts.approvals' | 'pr.merge.conflictsN' | 'pr.description.moreLines' | 'decomposition.issues' | 'decomposition.blockers' | 'decomposition.suggestions' | 'pr.block.base.merged' | 'design.send.all' | 'usage.panel.count';

/** Picks the `.one` / `.other` variant of `family` by `count`, then fills it like `t`. */
export function tPlural(family: PluralFamily, count: number, vars?: Record<string, string | number>): string {
  const key: `${PluralFamily}.one` | `${PluralFamily}.other` = `${family}.${count === 1 ? 'one' : 'other'}`;
  return t(key, vars);
}

/** The task's last-event line. `tool` is already the text the reducer built (the caller escapes it); `waiting` names the notification kind. */
export function workerEventText(event: WorkerEvent): string {
  if (event.kind === 'tool') return event.detail ?? '';
  return t(EVENT_KEY[event.kind], { detail: event.detail ?? '' });
}
